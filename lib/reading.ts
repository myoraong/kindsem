export function readingBySlug(slug: string) {
  return READINGS.find((item) => item.slug === slug)
}

export function readingsForCalc(slug: string) {
  return READINGS.filter((item) => item.calcs.includes(slug))
}

export function readingPath(slug: string) {
  return `/guide/${slug}/`
}

export const GUIDE_PATH = "/guide/"

export function readingParagraphs(item: ReadingArticle) {
  return item.sections.flatMap((section) => [...section.paragraphs])
}

export function readingBody(item: ReadingArticle) {
  return readingParagraphs(item).join("")
}

